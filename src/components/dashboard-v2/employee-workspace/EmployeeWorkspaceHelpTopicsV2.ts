function normalizeTitle(rawTitle: unknown) {
  return typeof rawTitle === "string" ? rawTitle.trim().replace(/\s+/g, " ") : "";
}

export function resolveEmployeeWorkspaceHelpTopicV2(rawTitle: unknown): WorkspaceHelpTopicV2 | null {
  const title = normalizeTitle(rawTitle);
  if (!title) return null;

  const exact = EXACT_TOPICS[title];
  if (exact) return exact;

  if (title.startsWith("تقويم ")) return ATTENDANCE_CALENDAR_CARD;
  if (/طلبات/.test(title) && !/تصفية|سجل|جاري|تعذر|لا توجد/.test(title)) return REQUEST_LIST_CARD;
  if (title.startsWith("بيانات مستند")) return DOCUMENT_DETAILS_CARD;
  if (/قالب شفت|قوالب شفت/.test(title)) return SHIFT_TEMPLATES_CARD;
  if (/تعيين/.test(title) && /شفت|موظفة/.test(title)) return SHIFT_ASSIGNMENT_CARD;
  if (/استثناء/.test(title)) return SHIFT_EXCEPTIONS_CARD;

  return null;
}
